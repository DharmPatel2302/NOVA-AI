import mongoose from "mongoose";

const messageSchema = new mongoose.Schema(
  {
    conversationId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Conversation",
      required: true,
      index: true, // Frequent query: "all messages in a conversation"
    },
    role: {
      type: String,
      enum: ["user", "assistant"],
      required: true,
    },
    content: {
      type: String,
      required: true,
    },
    /**
     * The agent that generated this response (e.g., 'search', 'chat', 'coding', etc.).
     * Used by router to maintain agent continuity on follow-up messages.
     */
    agentType: {
      type: String,
      default: null,
    },
    /**
     * Images from Tavily search results — only populated for assistant
     * messages generated by the search agent. Empty array for all other messages.
     * Stored alongside the message so images persist and display correctly
     * on page refresh (not just in the initial optimistic response).
     */
    searchImages: {
      type: [
        {
          url: { type: String, required: true },
          description: { type: String, default: "" },
        },
      ],
      default: [],
    },
    /**
     * Short project title for coding artifacts (e.g. "Calculator App").
     * null for non-code-generation messages.
     */
    artifactTitle: {
      type: String,
      default: null,
    },
    /**
     * Generated code files for code_generation coding intent.
     * Shape: [{ filename, language, content }]. Empty for non-coding messages.
     */
    artifactFiles: {
      type: [
        {
          filename: { type: String, required: true },
          language: { type: String, required: true },
          content: { type: String, required: true },
        },
      ],
      default: [],
    },
    /**
     * Permanent Cloudinary URL for AI-generated images (from image agent).
     * Unlike the old S3 keys, these URLs never expire — no refresh needed.
     */
    generatedImageUrl: {
      type: String,
      default: null,
    },
    /**
     * Cloudinary public_id for the generated image (needed for cleanup on deletion).
     */
    generatedImagePublicId: {
      type: String,
      default: null,
    },
    /**
     * Permanent Cloudinary URL for AI-generated PDF reports (from PDF agent).
     * Unlike the old S3 keys, these URLs never expire — no refresh needed.
     */
    generatedPdfUrl: {
      type: String,
      default: null,
    },
    /**
     * Cloudinary public_id for the generated PDF (needed for cleanup on deletion).
     */
    generatedPdfPublicId: {
      type: String,
      default: null,
    },
    /**
     * Display title for the generated PDF (used as label + download filename).
     */
    pdfTitle: {
      type: String,
      default: null,
    },
    /**
     * Permanent Cloudinary URL for AI-generated presentations (from PPT agent).
     * Unlike the old S3 keys, these URLs never expire — no refresh needed.
     */
    generatedPptUrl: {
      type: String,
      default: null,
    },
    /**
     * Cloudinary public_id for the generated PPT (needed for cleanup on deletion).
     */
    generatedPptPublicId: {
      type: String,
      default: null,
    },
    /**
     * Display title for the generated PPT (used as label + download filename).
     */
    pptTitle: {
      type: String,
      default: null,
    },
  },
  {
    timestamps: true, // Adds createdAt automatically
  }
);

const Message = mongoose.model("Message", messageSchema);

export default Message;
