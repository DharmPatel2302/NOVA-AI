import PDFDocument from "pdfkit";

/**
 * Generates a well-formatted PDF document as a Buffer from structured content.
 *
 * PDFKit STREAMING MODEL (important for understanding this code):
 * PDFKit's PDFDocument is a Node.js Readable stream — it does NOT build the
 * entire PDF in a single in-memory buffer and then return it. Instead, as you
 * call writing methods (.text(), .moveDown(), etc.), binary PDF chunks are
 * emitted incrementally via 'data' events. To get a final Buffer suitable for
 * S3 upload, we collect these chunks into an array and concatenate them when
 * the stream ends. There is no .toBuffer() method — this chunk-collection
 * approach is how PDFKit is designed to work.
 *
 * @param {Object} params
 * @param {string} params.title - Document title (defaults to "Nova AI Report" if missing)
 * @param {string|null} params.subtitle - Optional subtitle
 * @param {Array<{heading: string, content: string, bullets: string[]|null}>} params.sections
 * @returns {Promise<Buffer>} The complete PDF file as a Buffer
 */
export const generatePdfBuffer = ({ title, subtitle, sections }) => {
  return new Promise((resolve, reject) => {
    try {
      // ─── Defaults & validation ──────────────────────────────────────
      const safeTitle = (typeof title === "string" && title.trim()) ? title.trim() : "Nova AI Report";
      const safeSubtitle = (typeof subtitle === "string" && subtitle.trim()) ? subtitle.trim() : null;

      // Ensure sections is a non-empty array; fall back to a minimal placeholder
      let safeSections = [];
      if (Array.isArray(sections) && sections.length > 0) {
        safeSections = sections.map((s, i) => {
          // Coerce/validate each section's fields defensively
          const heading = (typeof s.heading === "string" && s.heading.trim())
            ? s.heading.trim()
            : `Section ${i + 1}`;
          const content = typeof s.content === "string"
            ? s.content.trim()
            : (s.content ? String(s.content) : "");
          const bullets = Array.isArray(s.bullets)
            ? s.bullets.filter((b) => typeof b === "string" && b.trim()).map((b) => b.trim())
            : null;
          return { heading, content, bullets };
        });
      } else {
        safeSections = [
          {
            heading: "Report",
            content: "No detailed content was generated for this request.",
            bullets: null,
          },
        ];
      }

      // ─── Create PDFDocument ─────────────────────────────────────────
      const doc = new PDFDocument({
        size: "A4",
        margins: { top: 50, bottom: 50, left: 50, right: 50 },
        bufferPages: true, // REQUIRED — enables post-generation page numbering
        info: {
          Title: safeTitle,
          Author: "Nova AI",
          Creator: "Nova AI",
          Subject: safeSubtitle || safeTitle,
        },
      });

      // ─── Chunk-based buffer collection ──────────────────────────────
      // PDFKit streams PDF data in chunks via 'data' events as content is written.
      // We collect all chunks and concatenate them into a single Buffer on 'end'.
      const chunks = [];
      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", (err) => reject(new Error(`PDF generation stream error: ${err.message}`)));

      // ─── Design constants ───────────────────────────────────────────
      const ACCENT_COLOR = "#4338CA"; // Deep indigo
      const TEXT_COLOR = "#2a2a2a";
      const MUTED_COLOR = "#999999";
      const HEADING_COLOR = "#555555";
      const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

      // ─── STEP 1: Title page / header ────────────────────────────────
      doc
        .fontSize(24)
        .font("Helvetica-Bold")
        .fillColor("#1a1a1a")
        .text(safeTitle, { align: "center" });

      if (safeSubtitle) {
        doc
          .moveDown(0.5)
          .fontSize(13)
          .font("Helvetica")
          .fillColor(HEADING_COLOR)
          .text(safeSubtitle, { align: "center" });
      }

      // Generation timestamp
      const dateStr = new Date().toLocaleDateString("en-US", {
        year: "numeric",
        month: "long",
        day: "numeric",
      });
      doc
        .moveDown(0.3)
        .fontSize(9)
        .fillColor(MUTED_COLOR)
        .text(`Generated by Nova AI on ${dateStr}`, { align: "center" });

      // Subtle horizontal divider
      doc.moveDown(1);
      const dividerY = doc.y;
      doc
        .moveTo(doc.page.margins.left, dividerY)
        .lineTo(doc.page.width - doc.page.margins.right, dividerY)
        .strokeColor("#e0e0e0")
        .lineWidth(1)
        .stroke();
      doc.moveDown(1.5);

      // ─── STEP 2: Sections loop ─────────────────────────────────────
      for (const section of safeSections) {
        // Section heading
        doc
          .fontSize(16)
          .font("Helvetica-Bold")
          .fillColor(ACCENT_COLOR)
          .text(section.heading)
          .moveDown(0.4);

        // Section body content
        if (section.content) {
          doc
            .fontSize(11)
            .font("Helvetica")
            .fillColor(TEXT_COLOR)
            .text(section.content, { align: "justify", lineGap: 4 })
            .moveDown(0.5);
        }

        // Section bullets (only when genuinely present)
        if (section.bullets && section.bullets.length > 0) {
          for (const bullet of section.bullets) {
            doc
              .fontSize(11)
              .font("Helvetica")
              .fillColor(TEXT_COLOR)
              .text(`•  ${bullet}`, { indent: 15, lineGap: 3 });
            doc.moveDown(0.3);
          }
          doc.moveDown(0.5);
        }

        // Space between sections
        doc.moveDown(1);
      }

      // ─── STEP 3: Footer / page numbers ─────────────────────────────
      // bufferedPageRange() returns { start, count } of all generated pages.
      // switchToPage(i) lets us draw on any page after content generation.
      // This MUST happen before doc.end().
      const range = doc.bufferedPageRange();
      for (let i = range.start; i < range.start + range.count; i++) {
        doc.switchToPage(i);
        doc
          .fontSize(8)
          .fillColor(MUTED_COLOR)
          .text(
            `Page ${i + 1} of ${range.count}`,
            50,
            doc.page.height - 30,
            { align: "center", width: doc.page.width - 100 }
          );
      }

      // ─── STEP 4: Finalize ──────────────────────────────────────────
      // doc.end() signals that no more content will be added and triggers
      // the 'end' event once the stream finishes flushing all remaining chunks.
      doc.end();
    } catch (error) {
      reject(new Error(`PDF generation failed: ${error.message}`));
    }
  });
};
