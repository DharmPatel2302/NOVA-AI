import pptxgen from "pptxgenjs";

/**
 * Consistent theme used across ALL slides in a generated deck.
 * Centralizing colors here ensures visual consistency — the single biggest
 * difference between a professional deck and an amateur one.
 */
const THEME = {
  primaryColor: "4338CA", // Deep indigo
  accentColor: "F59E0B",  // Warm amber
  textDark: "2A2A2A",
  textMuted: "666666",
  bgLight: "F7F7FA",
};

/**
 * Generates a well-formatted PowerPoint presentation as a Buffer from structured content.
 *
 * Uses pptxgenjs's in-memory buffer generation (pptx.write({ outputType: 'nodebuffer' }))
 * — NOT writeFile(), since the output goes to S3, not local disk.
 *
 * @param {Object} params
 * @param {string} params.title - Presentation title (defaults to "Nova AI Presentation" if missing)
 * @param {string|null} params.subtitle - Optional subtitle
 * @param {Array<{heading: string, bullets: string[]|null, content: string|null}>} params.slides
 * @returns {Promise<Buffer>} The complete .pptx file as a Buffer
 */
export const generatePptBuffer = async ({ title, subtitle, slides }) => {
  try {
    // ─── Defaults & validation ──────────────────────────────────────
    const safeTitle =
      typeof title === "string" && title.trim() ? title.trim() : "Nova AI Presentation";
    const safeSubtitle =
      typeof subtitle === "string" && subtitle.trim() ? subtitle.trim() : null;

    // Ensure slides is a non-empty array; fall back to a minimal placeholder
    let safeSlides = [];
    if (Array.isArray(slides) && slides.length > 0) {
      safeSlides = slides.map((s, i) => {
        const heading =
          typeof s.heading === "string" && s.heading.trim()
            ? s.heading.trim()
            : `Slide ${i + 1}`;
        const bullets =
          Array.isArray(s.bullets) && s.bullets.length > 0
            ? s.bullets.filter((b) => typeof b === "string" && b.trim()).map((b) => b.trim())
            : null;
        const content =
          typeof s.content === "string" && s.content.trim() ? s.content.trim() : null;
        return { heading, bullets, content };
      });
    } else {
      safeSlides = [
        {
          heading: "Presentation",
          bullets: null,
          content: "No detailed content was generated for this request.",
        },
      ];
    }

    // ─── Create presentation ──────────────────────────────────────
    const pptx = new pptxgen();
    pptx.author = "Nova AI";
    pptx.company = "Nova AI";
    pptx.title = safeTitle;
    pptx.layout = "LAYOUT_WIDE"; // 16:9 widescreen — modern standard

    // ─── COVER SLIDE ──────────────────────────────────────────────
    const coverSlide = pptx.addSlide();
    coverSlide.background = { color: THEME.primaryColor };

    coverSlide.addText(safeTitle, {
      x: 0.5,
      y: 2.6,
      w: "90%",
      h: 1.2,
      fontSize: 36,
      bold: true,
      color: "FFFFFF",
      align: "center",
      fontFace: "Helvetica",
    });

    if (safeSubtitle) {
      coverSlide.addText(safeSubtitle, {
        x: 0.5,
        y: 3.8,
        w: "90%",
        h: 0.6,
        fontSize: 18,
        color: "E8E8F0",
        align: "center",
        fontFace: "Helvetica",
      });
    }

    coverSlide.addText("Generated by Nova AI", {
      x: 0.5,
      y: 6.8,
      w: "90%",
      h: 0.4,
      fontSize: 11,
      color: "CCCCDD",
      align: "center",
    });

    // ─── CONTENT SLIDES ───────────────────────────────────────────
    safeSlides.forEach((slide, slideIndex) => {
      const contentSlide = pptx.addSlide();
      contentSlide.background = { color: "FFFFFF" };

      // Heading
      contentSlide.addText(slide.heading, {
        x: 0.5,
        y: 0.4,
        w: "90%",
        h: 0.8,
        fontSize: 26,
        bold: true,
        color: THEME.primaryColor,
        fontFace: "Helvetica",
      });

      // Accent line beneath heading
      contentSlide.addShape(pptx.shapes.RECTANGLE, {
        x: 0.5,
        y: 1.15,
        w: 1.2,
        h: 0.05,
        fill: { color: THEME.accentColor },
      });

      // Body content — bullets or paragraph
      if (slide.bullets && slide.bullets.length > 0) {
        // Bulleted text block using pptxgenjs's array-of-objects text API
        const bulletRows = slide.bullets.map((b) => ({
          text: b,
          options: { bullet: true, breakLine: true },
        }));

        contentSlide.addText(bulletRows, {
          x: 0.6,
          y: 1.5,
          w: "85%",
          h: 4.5,
          fontSize: 16,
          color: THEME.textDark,
          valign: "top",
          lineSpacingMultiple: 1.3,
          fontFace: "Helvetica",
        });
      } else if (slide.content) {
        // Paragraph form
        contentSlide.addText(slide.content, {
          x: 0.6,
          y: 1.5,
          w: "85%",
          h: 4.5,
          fontSize: 15,
          color: THEME.textDark,
          valign: "top",
          align: "left",
          lineSpacingMultiple: 1.2,
          fontFace: "Helvetica",
        });
      } else {
        // Malformed slide — heading rendered, body skipped
        console.warn(`[GeneratePpt] Slide ${slideIndex + 1} ("${slide.heading}") has no bullets or content — skipping body.`);
      }

      // Slide number footer
      contentSlide.addText(`${slideIndex + 2}`, {
        x: "92%",
        y: "93%",
        w: 0.5,
        h: 0.3,
        fontSize: 10,
        color: THEME.textMuted,
        align: "right",
      });
    });

    // ─── CLOSING SLIDE ────────────────────────────────────────────
    const closingSlide = pptx.addSlide();
    closingSlide.background = { color: THEME.bgLight };

    closingSlide.addText("Thank You", {
      x: 0.5,
      y: 2.8,
      w: "90%",
      h: 1.0,
      fontSize: 36,
      bold: true,
      color: THEME.primaryColor,
      align: "center",
      fontFace: "Helvetica",
    });

    closingSlide.addText("Generated by Nova AI", {
      x: 0.5,
      y: 6.8,
      w: "90%",
      h: 0.4,
      fontSize: 11,
      color: THEME.textMuted,
      align: "center",
    });

    // ─── Generate buffer ──────────────────────────────────────────
    // pptx.write({ outputType: 'nodebuffer' }) returns the .pptx as an
    // in-memory Buffer — this is the correct method for S3 upload
    // (do NOT use writeFile which writes to local disk).
    const buffer = await pptx.write({ outputType: "nodebuffer" });
    return buffer;
  } catch (error) {
    throw new Error(`PPT generation failed: ${error.message}`);
  }
};
